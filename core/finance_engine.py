    def verify_double_entry_balance(self, entries: List[Dict[str, Any]]) -> bool:
        """
        Проверяет математическое равенство дебетовых и кредитовых оборотов по журналу проводок.
        """
        total_dt = sum(item["sum"] for item in entries)
        total_kt = sum(item["sum"] for item in entries)
        is_balanced = abs(total_dt - total_kt) < 0.01
        logger.info(f"Проверка двойной записи: Всего Дт = {total_dt}, Всего Кт = {total_kt}. Баланс: {is_balanced}")
        return is_balanced

    def calculate_account_balances(self, initial_balances: Dict[str, float] = None) -> Dict[str, Dict[str, float]]:
        """
        Высчитывает начальное сальдо, дебетовый/кредитовый оборот и конечное сальдо по каждому счету.
        """
        init_b = initial_balances or {
            "51": 250000.0, "10": 120000.0, "60": 50000.0, "62": 80000.0, "70": 40000.0, "43": 100000.0
        }
        
        entries = self.generate_journal_entries()
        account_summary = {}

        for acc_code, acc_meta in self.accounts.items():
            dt_turnover = sum(e["sum"] for e in entries if e["dt"].startswith(acc_code))
            kt_turnover = sum(e["sum"] for e in entries if e["kt"].startswith(acc_code))
            sal_init = init_b.get(acc_code, 0.0)

            if acc_meta["type"] == "active":
                sal_end = sal_init + dt_turnover - kt_turnover
            elif acc_meta["type"] == "passive":
                sal_end = sal_init + kt_turnover - dt_turnover
            else:
                sal_end = sal_init + dt_turnover - kt_turnover

            account_summary[acc_code] = {
                "name": acc_meta["name"],
                "type": acc_meta["type"],
                "initial_balance": sal_init,
                "dt_turnover": dt_turnover,
                "kt_turnover": kt_turnover,
                "final_balance": sal_end
            }

        return account_summary

